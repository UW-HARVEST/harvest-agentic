"""Rust constants for probe values (probe --rust)."""
import os
import struct

from . import VERSION, die
from .emit import (INT_BITS, RUST_INT, STRING_TYPES, Emitter, TranslateError, field_ident, float_literal, shorten,
                   str_literal)
from .rustcheck import check_rust

INT_CHOICES = ['c'] + sorted(INT_BITS)


def fits(v, rt):
    bits, signed = INT_BITS[rt]
    return (-(1 << (bits - 1)) <= v < 1 << (bits - 1)) if signed else 0 <= v < 1 << bits


def item(kind, v, size, signed, int_type, str_type):
    """(Rust type, Rust value) of one probe value. int_type 'c' uses the size and sign of the C type."""
    if kind == 'int':
        rt = RUST_INT[(size, signed)] if int_type == 'c' else int_type
        return rt, Emitter.int_literal(v, rt, 'dec')
    if kind == 'float':
        if size == 4:  # the probe stored the C float as a double: convert back, exact
            bits = struct.unpack('<I', struct.pack('<f', struct.unpack('<d', struct.pack('<Q', v))[0]))[0]
            return 'f32', float_literal(bits, 4)
        return 'f64', float_literal(v, 8)
    st = STRING_TYPES[str_type]
    return (f'Option<{st}>', 'None') if v is None else (st, str_literal(v, str_type))


def write(path, vals, int_type, str_type, origin):
    """Write one `pub const` for each value. Returns False if rustc rejects the file."""
    bad = [f'{n}={v}' for n, (k, v, _, _) in vals.items() if k == 'int' and int_type != 'c' and not fits(v, int_type)]
    if bad:
        die(f'values do not fit {int_type}: {", ".join(bad[:20])}. Use a wider --int-type, or the default "c".')
    lines, counts = [], {}
    for n, (kind, v, size, signed) in vals.items():
        try:
            rt, lit = item(kind, v, size, signed, int_type, str_type)
        except TranslateError as e:
            die(f'{n}: {e}')
        counts[rt] = counts.get(rt, 0) + 1
        lines.append(f'pub const {field_ident(n)}: {rt} = {lit};')
    if not lines:
        die('no values to write')
    text = (f'// Generated by tab2rust {VERSION} probe {origin}. Do not edit by hand.\n'
            '// Values are the compiled C values for this build configuration.\n'
            '#![allow(non_upper_case_globals, dead_code)]\n\n' + '\n'.join(lines) + '\n')
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    print(f'wrote {path} ({len(lines)} constants: {", ".join(f"{c} {t}" for t, c in counts.items())})')
    print(f'  first   {shorten(lines[0], 100)}')
    print(f'  last    {shorten(lines[-1], 100)}')
    return check_rust(path)
